#!/usr/bin/env python3
"""
perf_report.py - collect the PERF lines of a performance regression and write
                 perf_results.csv + perf_results.md (one table per variant / suite)

  python scripts/run_sim.py regress -l tb/uvm/regress/regress_perf.txt --variants default,d32,d128
  python scripts/perf_report.py sim/regress/<stamp> [-o docs/perf_results.md]

PERF line format (tests/perf, dma_perf_base::measure):
  PERF,<suite>,<case>,key=value,...
"""
import argparse, csv, glob, os, re, sys
from collections import OrderedDict, defaultdict

BUSW = {"default": 64, "d32": 32, "d128": 128}
# columns shown first (when present), the rest follow in first-seen order
FIRST = ["case", "ch", "bytes", "cyc", "bpc", "eff", "bus", "lat0", "tail", "rlat", "ar", "aw", "ord", "owr"]
HIDE = {"link"}

def parse(rdir):
    rows = []
    for log in sorted(glob.glob(os.path.join(rdir, "*", "sim.log"))):
        run = os.path.basename(os.path.dirname(log))
        variant = run.split("_dma_")[0]
        for line in open(log, errors="replace"):
            m = re.search(r"\bPERF,([^,\s]+),([^,\s]+),(\S+)", line)
            if not m:
                continue
            r = OrderedDict(variant=variant, suite=m.group(1), case=m.group(2))
            for kv in m.group(3).split(","):
                if "=" in kv:
                    k, v = kv.split("=", 1)
                    r[k] = v
            rows.append(r)
    return rows

def table(rows):
    cols = [c for c in FIRST if any(c in r for r in rows)]
    for r in rows:
        for k in r:
            if k not in cols and k not in ("variant", "suite") and k not in HIDE:
                cols.append(k)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(r.get(c, "") for c in cols) + " |")
    return "\n".join(out)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rdir")
    ap.add_argument("-o", "--out", default=None)
    a = ap.parse_args()
    rows = parse(a.rdir)
    if not rows:
        sys.exit("no PERF lines found in %s" % a.rdir)
    keys = []
    for r in rows:
        for k in r:
            if k not in keys:
                keys.append(k)
    with open(os.path.join(a.rdir, "perf_results.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in rows:
            w.writerow(r)
    groups = defaultdict(list)
    for r in rows:
        groups[(r["variant"], r["suite"])].append(r)
    md = ["# Performance results (generated)", "",
          "Generated by `scripts/perf_report.py` from `%s`." % os.path.relpath(a.rdir).replace("\\", "/"),
          "Units: cycles of ACLK; `bpc` payload bytes per cycle; `eff` = bpc / bus bytes (%).",
          "See `docs/perf_report.md` for the analysis.", ""]
    for (v, s) in sorted(groups, key=lambda k: (list(BUSW).index(k[0]) if k[0] in BUSW else 99, k[1])):
        md += ["## %s (%s, %d-bit bus)" % (s, v, BUSW.get(v, 0)), "", table(groups[(v, s)]), ""]
    txt = "\n".join(md)
    out = a.out or os.path.join(a.rdir, "perf_results.md")
    open(out, "w").write(txt + "\n")
    print("%d PERF rows -> %s" % (len(rows), out))

if __name__ == "__main__":
    main()
